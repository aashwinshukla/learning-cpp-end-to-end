// or call it immediately right where it's defined

// syntax:
// [capture list] (parameters) -> return type { body };
//
// capture list  = variables from the surrounding scope you want to use inside the lambda
// parameters    = inputs just like a regular function
// -> return type = optional, compiler usually figures it out
